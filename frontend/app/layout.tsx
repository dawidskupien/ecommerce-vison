import type { Metadata } from "next";
import "./styles/globals.css";
import { SessionProvider } from "next-auth/react";
import { Inter, Roboto } from "next/font/google";
import { ReactQueryClientProvider } from "@/providers/query-client";
import { ReactQueryDevtools } from "@tanstack/react-query-devtools";
import { SessionAuthProvider } from "@/providers/session";
import { QueryParamsProvider } from "@/providers/use-params";
import { NavigationStoreProvider } from "@/providers/navigation-store-provider";
import { CartStoreProvider } from "@/providers/cart-store-provider";

export const inter = Inter({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-inter",
  weight: ["300", "400", "500", "600", "700"],
  fallback: ["sans-serif"],
});

export const roboto = Roboto({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-roboto",
  weight: ["300", "400", "500", "700"],
  fallback: ["sans-serif"],
});

export const metadata: Metadata = {
  title: "Homepage",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
          <body className={`${inter.variable} ${roboto.variable}`}>
              <SessionAuthProvider>
                  <NavigationStoreProvider>
                    <CartStoreProvider>
                    <ReactQueryClientProvider>
                      <QueryParamsProvider>
                        {children}
                        {process.env.NODE_ENV === "development" && (
                          <ReactQueryDevtools />
                        )}
                      </QueryParamsProvider>
                    </ReactQueryClientProvider>
                    </CartStoreProvider>
                  </NavigationStoreProvider>
              </SessionAuthProvider>
          </body>
    </html>
  );
}
